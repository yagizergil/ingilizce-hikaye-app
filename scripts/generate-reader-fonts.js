/**
 * generate-reader-fonts.js
 *
 * One-off dev script (first entry in scripts/ — no prior convention
 * existed, so this establishes one: reusable Node generators that produce
 * committed source files live in scripts/, run by hand when their inputs
 * change). Reads the two Literata TTF files already vendored by
 * @expo-google-fonts/literata and writes them out as base64 string
 * constants consumed by src/features/reader/webview/buildReaderHtml.ts.
 *
 * WHY: the reader WebView's <style> needs @font-face data URIs, and at
 * runtime buildReaderHtml.ts cannot read files off disk (no `fs` in the
 * RN/Hermes runtime). Pre-baking the base64 at dev time avoids bundling a
 * font-loading step into the WebView HTML entirely.
 *
 * Run with: node scripts/generate-reader-fonts.js
 * Re-run only if @expo-google-fonts/literata is upgraded to a new font
 * revision.
 */
const fs = require("fs");
const path = require("path");

const ROOT = process.cwd();
const OUT_DIR = path.join(ROOT, "src", "features", "reader", "webview", "fonts");

const FONTS = [
  {
    src: path.join(
      ROOT,
      "node_modules",
      "@expo-google-fonts",
      "literata",
      "400Regular",
      "Literata_400Regular.ttf",
    ),
    outFile: path.join(OUT_DIR, "literataRegularBase64.ts"),
    exportName: "literataRegularBase64",
  },
  {
    src: path.join(
      ROOT,
      "node_modules",
      "@expo-google-fonts",
      "literata",
      "400Regular_Italic",
      "Literata_400Regular_Italic.ttf",
    ),
    outFile: path.join(OUT_DIR, "literataItalicBase64.ts"),
    exportName: "literataItalicBase64",
  },
];

for (const font of FONTS) {
  const buffer = fs.readFileSync(font.src);
  const base64 = buffer.toString("base64");
  const content =
    `// AUTO-GENERATED by scripts/generate-reader-fonts.js — do not hand-edit.\n` +
    `// Source: ${path.relative(ROOT, font.src).replace(/\\/g, "/")}\n` +
    `export const ${font.exportName} = "${base64}";\n`;
  fs.writeFileSync(font.outFile, content, "utf8");
  // eslint-disable-next-line no-console -- dev-only CLI script output
  console.log(
    `${path.relative(ROOT, font.outFile)}: ${buffer.length} bytes ttf -> ${base64.length} bytes base64 text (${(content.length / 1024).toFixed(1)} KB file)`,
  );
}
